import { describe, expect, it } from "vitest";
import { josa, withJosa } from "./josa.js";

/**
 * 조사 자동 선택 (2026-08-25 판정 A-L5)
 *
 * 실측: 영어 유닛 완주 안내가 **"다음 코스 일상 말하기은 지금 준비하고 있어요."** 로 나온다.
 * `UnitStudyPage.jsx:386-389`가 `은`·`로`를 **고정 문자열**로 붙이기 때문이다.
 * 일본어는 코스명 뒤에 `(JLPT N4)`가 붙어 드러나지 않았을 뿐, 규칙이 없기는 마찬가지다.
 *
 * 이름(코스명·닉네임·유닛 제목)을 문장에 넣는 자리는 계속 늘어난다 — 그때마다 손으로 고르지 않도록
 * **순수 함수 하나**로 고정한다. 화면은 이 함수만 부른다.
 *
 * 판정 규칙:
 *   - 한글 음절: 받침 유무로 고른다((코드 - 0xAC00) % 28)
 *   - 숫자: 한국어 읽기의 받침으로 고른다(1 일·7 칠·8 팔 = ㄹ받침, 3 삼·6 육·0 영 = 받침, 2·4·5·9 = 받침 없음)
 *   - **괄호·따옴표로 끝나면 그 안의 마지막 글자**를 본다 — "초급(JLPT N4)"는 "4"로 판정한다
 *   - 판정할 수 없는 글자(영문 등)로 끝나면 **받침 없음**으로 본다(더 흔하고 어색함이 덜하다)
 *   - `로/으로`만 규칙이 다르다: 받침이 없거나 **ㄹ 받침**이면 `로`
 *
 * 이 테스트를 수정하지 말 것 — 계약 변경은 senior-dev 경유.
 */

describe("josa — 은/는 (A-L5)", () => {
  it("받침이 없으면 는, 있으면 은", () => {
    expect(josa("일상 말하기", "은/는")).toBe("는"); // 실측 결함 문구의 주인공
    expect(josa("다시 세우기", "은/는")).toBe("는");
    expect(josa("이어 말하기", "은/는")).toBe("는");
    expect(josa("뉘앙스", "은/는")).toBe("는");
    expect(josa("실전과 격식", "은/는")).toBe("은");
    expect(josa("왕초보", "은/는")).toBe("는");
    expect(josa("중상급", "은/는")).toBe("은");
  });

  it("괄호로 끝나면 괄호 안 마지막 글자로 판정한다 — 일본어 코스 표기가 그렇다", () => {
    expect(josa("초급(JLPT N4)", "은/는")).toBe("는"); // 4 = 사
    expect(josa("중급(JLPT N3)", "은/는")).toBe("은"); // 3 = 삼
    expect(josa("왕초보(JLPT N5)", "은/는")).toBe("는"); // 5 = 오
    expect(josa("고급(JLPT N1)", "은/는")).toBe("은"); // 1 = 일(ㄹ 받침)
  });

  it("숫자로 끝나면 한국어 읽기의 받침을 따른다", () => {
    expect(josa("코스 1", "은/는")).toBe("은");
    expect(josa("코스 2", "은/는")).toBe("는");
    expect(josa("코스 3", "은/는")).toBe("은");
    expect(josa("유닛 10", "은/는")).toBe("은"); // 0 = 영
  });
});

describe("josa — 이/가 · 을/를 · 와/과", () => {
  it("같은 받침 규칙을 쓴다", () => {
    expect(josa("일상 말하기", "이/가")).toBe("가");
    expect(josa("실전과 격식", "이/가")).toBe("이");
    expect(josa("일상 말하기", "을/를")).toBe("를");
    expect(josa("실전과 격식", "을/를")).toBe("을");
    expect(josa("일상 말하기", "와/과")).toBe("와");
    expect(josa("실전과 격식", "와/과")).toBe("과");
  });
});

describe("josa — 로/으로 (규칙이 다르다)", () => {
  it("받침이 없거나 ㄹ 받침이면 로", () => {
    expect(josa("다시 세우기", "로/으로")).toBe("로");
    expect(josa("서울", "로/으로")).toBe("로"); // ㄹ 받침
    expect(josa("고급(JLPT N1)", "로/으로")).toBe("로"); // 1 = 일
    expect(josa("실전과 격식", "로/으로")).toBe("으로");
    expect(josa("중급(JLPT N3)", "로/으로")).toBe("으로");
  });
});

describe("withJosa — 이름과 조사를 붙여 준다", () => {
  it("문장에 그대로 끼울 수 있는 한 덩이를 돌려준다", () => {
    expect(withJosa("일상 말하기", "은/는")).toBe("일상 말하기는");
    expect(withJosa("초급(JLPT N4)", "로/으로")).toBe("초급(JLPT N4)로");
  });

  it("판정할 수 없는 글자로 끝나면 받침 없음으로 본다", () => {
    expect(withJosa("get up", "은/는")).toBe("get up는");
    expect(josa("", "은/는")).toBe("는");
    expect(josa(null, "은/는")).toBe("는");
  });
});
